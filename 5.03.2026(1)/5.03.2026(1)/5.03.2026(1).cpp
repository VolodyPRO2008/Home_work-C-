#define _CRT_SECURE_NO_WARNINGS

#include <iostream>
#include "Circle.h"
#include "Airplane.h"

using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");





    cout << "\n\n ЗАДАНИЕ 1: КЛАСС CIRCLE (ОКРУЖНОСТЬ) " << endl;

    // Создание окружностей
    cout << "\n 1.1 Создание окружностей " << endl;
    Circle c1(5.0);
    Circle c2(5.0);
    Circle c3(7.0);

    cout << "\n Вывод окружностей " << endl;
    cout << "c1: " << c1 << endl;
    cout << "c2: " << c2 << endl;
    cout << "c3: " << c3 << endl;

    // Проверка на равенство радиусов (==)
    cout << "\n 1.2 Проверка на равенство радиусов (==) " << endl;
    if (c1 == c2) {
        cout << "c1 и c2: радиусы равны" << endl;
    }
    else {
        cout << "c1 и c2: радиусы не равны" << endl;
    }

    if (c1 == c3) {
        cout << "c1 и c3: радиусы равны" << endl;
    }
    else {
        cout << "c1 и c3: радиусы не равны" << endl;
    }

    // Сравнение длин окружностей (>)
    cout << "\n 1.3 Сравнение длин окружностей (>) " << endl;
    if (c3 > c1) {
        cout << "Длина окружности c3 больше длины c1" << endl;
    }
    else {
        cout << "Длина окружности c3 НЕ больше длины c1" << endl;
    }

    // Демонстрация операторов < и !=
    cout << "\n 1.4 Дополнительные сравнения (<, !=) " << endl;
    if (c1 < c3) {
        cout << "Длина окружности c1 меньше длины c3" << endl;
    }

    if (c1 != c3) {
        cout << "c1 и c3 - разные окружности" << endl;
    }

    // Пропорциональное изменение размеров (+=, -=)
    cout << "\n 1.5 Изменение размера (+=, -=) " << endl;
    cout << "c1 до изменения: " << c1 << endl;

    c1 += 2.5;
    cout << "c1 после += 2.5: " << c1 << endl;

    c1 -= 3.0;
    cout << "c1 после -= 3.0: " << c1 << endl;

    // Операторы + и - (создают новую окружность)
    cout << "\n 1.6 Операторы + и - (создание новой окружности) " << endl;
    Circle c4 = c2 + 3.0;
    cout << "c2 + 3 = " << c4 << endl;

    Circle c5 = c2 - 1.0;
    cout << "c2 - 1 = " << c5 << endl;

    // Ввод окружности с клавиатуры
    cout << "\n 1.7 Ввод окружности с клавиатуры " << endl;
    Circle c6;
    cin >> c6;
    cout << "Вы ввели: " << c6 << endl;


    cout << "\n\n ЗАДАНИЕ 2: КЛАСС AIRPLANE (САМОЛЁТ) " << endl;

    // Создание самолётов
    cout << "\n--- 2.1 Создание самолётов ---" << endl;
    Airplane a1("Боинг 747", 300, 250);
    Airplane a2("Боинг 747", 300, 150);
    Airplane a3("Airbus A380", 500, 400);

    cout << "\n--- Вывод самолётов ---" << endl;
    cout << "a1: " << a1 << endl;
    cout << "a2: " << a2 << endl;
    cout << "a3: " << a3 << endl;

    // Проверка на равенство типов (==)
    cout << "\n--- 2.2 Проверка на равенство типов (==) ---" << endl;
    if (a1 == a2) {
        cout << "a1 и a2: одинаковые типы самолётов" << endl;
    }
    else {
        cout << "a1 и a2: разные типы самолётов" << endl;
    }

    if (a1 == a3) {
        cout << "a1 и a3: одинаковые типы самолётов" << endl;
    }
    else {
        cout << "a1 и a3: разные типы самолётов" << endl;
    }

    // Сравнение по максимальному количеству пассажиров (>)
    cout << "\n--- 2.3 Сравнение по макс. пассажирам (>) ---" << endl;
    if (a3 > a1) {
        cout << "a3 (Airbus A380) вмещает больше пассажиров, чем a1 (Боинг 747)" << endl;
    }

    // Демонстрация оператора <
    cout << "\n--- 2.4 Оператор (<) ---" << endl;
    if (a1 < a3) {
        cout << "a1 вмещает меньше пассажиров, чем a3" << endl;
    }

    // Префиксный инкремент (++airplane) - увеличение пассажиров
    cout << "\n--- 2.5 Префиксный инкремент (++airplane) ---" << endl;
    cout << "a1 до ++: " << a1 << endl;
    ++a1;
    cout << "a1 после ++: " << a1 << endl;

    // Заполнение до максимума
    cout << "\n--- 2.6 Заполнение самолёта до максимума ---" << endl;
    Airplane a4("Боинг 737", 150, 148);
    cout << "a4: " << a4 << endl;

    ++a4;
    ++a4;  // Второй раз не должно добавиться (мест нет)
    ++a4;  // Третий раз не должно добавиться
    cout << "a4 после попыток добавления: " << a4 << endl;

    // Префиксный декремент (--airplane) - уменьшение пассажиров
    cout << "\n--- 2.7 Префиксный декремент (--airplane) ---" << endl;
    cout << "a4 до --: " << a4 << endl;
    --a4;
    cout << "a4 после --: " << a4 << endl;

    // Очистка самолёта
    cout << "\n--- 2.8 Очистка самолёта до нуля ---" << endl;
    Airplane a5("Embraer E195", 100, 3);
    cout << "a5: " << a5 << endl;

    while (a5.getCurrentPassengers() > 0) {
        --a5;
    }
    cout << "a5 после очистки: " << a5 << endl;

    // Демонстрация оператора !=
    cout << "\n--- 2.9 Оператор (!=) ---" << endl;
    if (a1 != a3) {
        cout << "a1 и a3 - разные самолёты" << endl;
    }

    // Ввод самолёта с клавиатуры
    cout << "\n--- 2.10 Ввод самолёта с клавиатуры ---" << endl;
    Airplane a6;
    cin >> a6;
    cout << "Вы ввели: " << a6 << endl;

    // Демонстрация оператора присваивания
    cout << "\n--- 2.11 Оператор присваивания (=) ---" << endl;
    Airplane a7;
    a7 = a3;
    cout << "a7 (скопирован из a3): " << a7 << endl;

    // Демонстрация конструктора копирования
    cout << "\n--- 2.12 Конструктор копирования ---" << endl;
    Airplane a8 = a1;
    cout << "a8 (копия a1): " << a8 << endl;



    return 0;
}