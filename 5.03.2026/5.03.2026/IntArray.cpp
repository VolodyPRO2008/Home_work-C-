#define _CRT_SECURE_NO_WARNINGS

#include "IntArray.h"

// ============================================
// КОНСТРУКТОР ПО УМОЛЧАНИЮ
// ============================================
// Создаёт пустой массив (data = nullptr, size = 0)
// Вызывается при: IntArray arr;
// ============================================
IntArray::IntArray() : data(nullptr), size(0) {
    cout << "[КОНСТРУКТОР ПО УМОЛЧАНИЮ] Создан пустой массив" << endl;
}

// ============================================
// КОНСТРУКТОР ОТ РАЗМЕРА
// ============================================
// Выделяет память под n элементов и заполняет нулями
// explicit запрещает неявное преобразование: IntArray arr = 10; (ошибка)
// Вызывается при: IntArray arr(10);
// ============================================
IntArray::IntArray(size_t n) : data(new int[n]()), size(n) {
    cout << "[КОНСТРУКТОР ОТ РАЗМЕРА] Создан массив из " << size << " элементов, заполненный нулями" << endl;
}

// ============================================
// КОНСТРУКТОР КОПИРОВАНИЯ
// ============================================
// Выполняет глубокое копирование: выделяет новую память и копирует данные
// Вызывается при:
//   1. IntArray arr2(arr1);
//   2. передача объекта по значению в функцию
//   3. возврат объекта по значению из функции (до C++17)
// ============================================
IntArray::IntArray(const IntArray& other) : data(nullptr), size(other.size) {
    if (size > 0) {
        data = new int[size];
        for (size_t i = 0; i < size; i++) {
            data[i] = other.data[i];
        }
    }
    cout << "[КОНСТРУКТОР КОПИРОВАНИЯ] Скопирован массив из " << size << " элементов" << endl;
}

// ============================================
// КОНСТРУКТОР ПЕРЕМЕЩЕНИЯ
// ============================================
// Передаёт владение ресурсом, обнуляя источник
// noexcept гарантирует, что не будет выброшено исключение (важно для std::vector)
// Вызывается при:
//   1. IntArray arr2(std::move(arr1));
//   2. возврат временного объекта из функции
//   3. при реаллокации std::vector (если noexcept)
// ============================================
IntArray::IntArray(IntArray&& other) noexcept
    : data(other.data), size(other.size) {
    // Обнуляем источник, чтобы он не удалил память при своём уничтожении
    other.data = nullptr;
    other.size = 0;
    cout << "[КОНСТРУКТОР ПЕРЕМЕЩЕНИЯ] Ресурс перемещён, источник обнулён" << endl;
}

// ============================================
// ДЕСТРУКТОР
// ============================================
// Освобождает динамически выделенную память
// Вызывается автоматически при уничтожении объекта
// ============================================
IntArray::~IntArray() {
    cout << "[ДЕСТРУКТОР] Удаление массива из " << size << " элементов";
    delete[] data;
    cout << " (память освобождена)" << endl;
    data = nullptr;
    size = 0;
}

// ============================================
// ОПЕРАТОР ПРИСВАИВАНИЯ КОПИРОВАНИЕМ
// ============================================
// Выполняет глубокое копирование с освобождением старой памяти
// Вызывается при: arr1 = arr2; (где arr1 уже существует)
// ============================================
IntArray& IntArray::operator=(const IntArray& other) {
    cout << "[ОПЕРАТОР ПРИСВАИВАНИЯ КОПИРОВАНИЕМ] Начало операции" << endl;

    // Проверка на самоприсваивание (arr1 = arr1)
    if (this == &other) {
        cout << "  Самоприсваивание, ничего не делаем" << endl;
        return *this;
    }

    // Освобождаем старую память
    delete[] data;

    // Копируем размер
    size = other.size;

    // Выделяем новую память и копируем данные
    if (size > 0) {
        data = new int[size];
        for (size_t i = 0; i < size; i++) {
            data[i] = other.data[i];
        }
    }
    else {
        data = nullptr;
    }

    cout << "  Скопировано " << size << " элементов" << endl;
    return *this;
}

// ============================================
// ОПЕРАТОР ПРИСВАИВАНИЯ ПЕРЕМЕЩЕНИЕМ
// ============================================
// Передаёт владение ресурсом, обнуляя источник
// noexcept гарантирует безопасность при работе с контейнерами
// Вызывается при: arr1 = std::move(arr2);
// ============================================
IntArray& IntArray::operator=(IntArray&& other) noexcept {
    cout << "[ОПЕРАТОР ПРИСВАИВАНИЯ ПЕРЕМЕЩЕНИЕМ] Начало операции" << endl;

    // Проверка на самоприсваивание
    if (this == &other) {
        cout << "  Самоприсваивание, ничего не делаем" << endl;
        return *this;
    }

    // Освобождаем старую память
    delete[] data;

    // Перемещаем ресурсы (забираем владение)
    data = other.data;
    size = other.size;

    // Обнуляем источник
    other.data = nullptr;
    other.size = 0;

    cout << "  Ресурс перемещён, источник обнулён" << endl;
    return *this;
}

// ============================================
// МЕТОД PRINT
// ============================================
// Выводит элементы массива на экран
// ============================================
void IntArray::print() const {
    cout << "Массив [" << size << " элементов]: ";
    if (size == 0 || data == nullptr) {
        cout << "пуст" << endl;
        return;
    }

    cout << "[ ";
    for (size_t i = 0; i < size; i++) {
        cout << data[i];
        if (i < size - 1) cout << ", ";
    }
    cout << " ]" << endl;
}

// ============================================
// ОПЕРАТОР ИНДЕКСАЦИИ (неконстантный)
// ============================================
int& IntArray::operator[](size_t index) {
    return data[index];
}

// ============================================
// ОПЕРАТОР ИНДЕКСАЦИИ (константный)
// ============================================
const int& IntArray::operator[](size_t index) const {
    return data[index];
}